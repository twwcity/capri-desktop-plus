// the next of the hundred, in a shuffled order kept across restarts (none twice till all are said)
export function nextTease(lang) {
  const list = TEASES[lang === 'th' ? 'th' : 'en'];
  const key = `capri.teases.${lang === 'th' ? 'th' : 'en'}`;
  let deck = [];
  try { deck = JSON.parse(localStorage.getItem(key) || '[]'); } catch { /* fresh deck */ }
  deck = deck.filter((i) => Number.isInteger(i) && i >= 0 && i < list.length);
  if (!deck.length) {
    deck = list.map((_, i) => i);
    for (let i = deck.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [deck[i], deck[j]] = [deck[j], deck[i]];
    }
  }
  const i = deck.shift();
  try { localStorage.setItem(key, JSON.stringify(deck)); } catch { /* this run only */ }
  return list[i];
}
